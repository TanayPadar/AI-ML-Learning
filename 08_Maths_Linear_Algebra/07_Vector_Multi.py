#Multiplication of 2 Vectors

#DOT Product
#A= (2, 1, 3)
#B= (4, 5, 2)

#V = 8 + 5 + 6 = 19
# So, 19 is the DOT Product

#CROSS Product
#It produces a new vector which is perpendicular of the original vectors
#A= (2, 1, 3)
#B= (4, 5, 2)

#V = (1*2 - 3*5)i - (2*2 - 3*4)j + (2*5 - 1*4)k
#V = (-13)i + (-8)j + (6)k
# So, (-13, -8, 6) is the CROSS Product

