#Intersection and Union Events

#1 - P(A ∩ B) = When intersection of events A and B occurs
#2 - P(A ∪ B) = When union of events A and B occurs (either A or B or both)

#Types of Events 
#1 - Mutually Exclusive - Two events cannot occur at the same time like coin is either H or T
#2 - Independent Evenets - Outcome of one doesnt affect the probability of other
#3 - Dependent Events - Outcome of one depends on other's probability
#4 - Complementary Events - One of two events must occur (either A or B)

