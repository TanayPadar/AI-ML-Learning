#Probability - Measure of likelihood of an event to occur 
#Ranges from 0 to 1 
#O - impossible event
#1 - certain event

#Sample Space (S) - all possible outcomes
#Event (E) - favourable outcomes
#P(E) = n(E) / n(S)
#n(E) - number of favourable outcomes
#n(S) - number of possible outcomes

#Example:
#Tossing a coin
#Sample Space (S) = {H, T}
#Event (E) = {H}
#P(E) = 1/2


